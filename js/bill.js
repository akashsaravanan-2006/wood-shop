// =========================================
// CFT SUMMARY
// =========================================

const cftSummary = {};


woodData.forEach(
    function (item) {

        let name =
            item.woodType || "Unknown";

        if (
            name === "Other" &&
            item.otherWood
        ) {

            name =
                item.otherWood;
        }


        const cft =
            Number(
                item.cubicFeet || 0
            );


        if (
            Object.prototype.hasOwnProperty
                .call(cftSummary, name)
        ) {

            cftSummary[name] += cft;

        }
        else {

            cftSummary[name] = cft;
        }

    }
);


// =========================================
// DISPLAY CFT SUMMARY
// =========================================

const cftDiv =
    document.getElementById("cftSummary");


if (cftDiv) {

    cftDiv.innerHTML = "";


    for (
        const wood in cftSummary
    ) {

        cftDiv.innerHTML += `

            <p>

                <b>
                    ${wood}
                </b>

                :

                ${cftSummary[wood]
                    .toFixed(2)}

                CFT

            </p>
        `;
    }
}


