// =========================================
// BILL DATE AND TIME
// =========================================

const billDateElement =
    document.getElementById("billDate");

const billDayTimeElement =
    document.getElementById("billDayTime");

const today = new Date();

const days = [
    "Sunday",
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday"
];

let savedDate =
    localStorage.getItem("billDate");

if (!savedDate) {

    savedDate =
        today.getDate().toString().padStart(2, "0") +
        "/" +
        (today.getMonth() + 1)
            .toString()
            .padStart(2, "0") +
        "/" +
        today.getFullYear();

    localStorage.setItem(
        "billDate",
        savedDate
    );
}

if (billDateElement) {

    billDateElement.textContent =
        savedDate;
}

if (billDayTimeElement) {

    const time =
        today.toLocaleTimeString("en-IN", {
            hour: "2-digit",
            minute: "2-digit",
            second: "2-digit",
            hour12: true
        });

    billDayTimeElement.textContent =
        days[today.getDay()] +
        " | " +
        time;
}


